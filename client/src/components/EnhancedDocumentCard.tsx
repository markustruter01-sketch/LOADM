import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { useLocation } from "wouter";
import { formatDistanceToNow } from "date-fns";
import { 
  Mail, 
  Download, 
  Share, 
  ExternalLink, 
  FileText,
  MoreHorizontal
} from "lucide-react";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";

interface DocumentData {
  id: string;
  title: string;
  description: string;
  type: string;
  category?: string;
  lastUpdated: Date;
  formRoute?: string;
}

interface EnhancedDocumentCardProps {
  document: DocumentData;
  onOpenForm?: (documentId: string, documentTitle: string) => void;
}

export default function EnhancedDocumentCard({ document, onOpenForm }: EnhancedDocumentCardProps) {
  const [, navigate] = useLocation();
  
  const formattedDate = formatDistanceToNow(document.lastUpdated, {
    addSuffix: true,
  });

  // Form route mapping
  const getFormRoute = (title: string): string => {
    const routeMap: Record<string, string> = {
      "Load Planning Form": "/cargo-manifest#load-planning-form",
      "Passenger/Crew and Cargo Manifest": "/cargo-manifest#cargo-manifest-form",
      "Dangerous Goods Declaration": "/cargo-manifest#dangerous-goods-declaration-form",
      "Weight & Balance Sheet": "/cargo-manifest#weight-balance-sheet-form",
      "Special Handling Form": "/cargo-manifest#special-handling-form",
      "Aircraft Tie-Down Diagram": "/cargo-manifest#tie-down-diagram-form",
      "Cargo Compatibility Checklist": "/cargo-manifest#compatibility-checklist-form",
      "Shoring Requirements Worksheet": "/cargo-manifest#shoring-worksheet-form",
      "Hazard Certification Form": "/cargo-manifest#hazard-certification-form",
      "Aircraft Loading Deviation Request": "/cargo-manifest#loading-deviation-form"
    };
    return routeMap[title] || "/cargo-manifest";
  };

  // Generate document content for download
  const generateDocumentContent = (): string => {
    const currentDate = new Date().toLocaleDateString();
    const currentTime = new Date().toLocaleTimeString();
    
    return `${document.title}
Generated from LOADMworkflow System

Document Information:
- Title: ${document.title}
- Type: ${document.type}
- Category: ${document.category || 'Standard Form'}
- Description: ${document.description}
- Last Updated: ${document.lastUpdated.toLocaleString()}
- Generated: ${currentDate} at ${currentTime}

Instructions:
This document template can be filled out and submitted through the LOADMworkflow application.
Please ensure all required fields are completed before submission.

For technical support or questions about this document, contact your system administrator.

---
Generated by LOADMworkflow Document Management System
Australian Defence Force - Cargo Operations
`;
  };

  // Handle opening the form inline
  const handleOpenForm = () => {
    // Instead of navigating, we'll use a callback to open the form inline
    if (onOpenForm) {
      onOpenForm(document.id, document.title);
    }
  };

  // Handle email sharing
  const handleEmailShare = () => {
    const subject = encodeURIComponent(`${document.title} - LOADMworkflow Document`);
    const documentContent = generateDocumentContent();
    
    const body = encodeURIComponent(
      `Hello,\n\n` +
      `Please find the ${document.title} document template below:\n\n` +
      `${documentContent}\n\n` +
      `You can access the interactive version at: ${window.location.origin}${getFormRoute(document.title)}\n\n` +
      `Best regards`
    );
    
    const mailtoLink = `mailto:?subject=${subject}&body=${body}`;
    window.open(mailtoLink, '_blank');
  };

  // Handle download to device
  const handleDownload = () => {
    const content = generateDocumentContent();
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    
    const link = window.document.createElement('a');
    link.href = url;
    link.download = `${document.title.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.txt`;
    window.document.body.appendChild(link);
    link.click();
    window.document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  // Handle native sharing (includes AirDrop on iOS/macOS)
  const handleNativeShare = async () => {
    const content = generateDocumentContent();
    
    if (navigator.share) {
      try {
        // Create a file for sharing
        const blob = new Blob([content], { type: 'text/plain' });
        const file = new File([blob], `${document.title.replace(/\s+/g, '_')}.txt`, { type: 'text/plain' });
        
        await navigator.share({
          title: document.title,
          text: `${document.title} - LOADMworkflow Document`,
          files: [file]
        });
      } catch (error) {
        console.log('Native sharing failed, falling back to download');
        handleDownload();
      }
    } else {
      // Fallback to download for browsers without native sharing
      handleDownload();
    }
  };

  // Handle copy link
  const handleCopyLink = async () => {
    const url = `${window.location.origin}${getFormRoute(document.title)}`;
    
    try {
      await navigator.clipboard.writeText(url);
      alert('Document link copied to clipboard!');
    } catch (error) {
      console.error('Failed to copy link:', error);
      // Fallback for older browsers
      const textArea = window.document.createElement('textarea');
      textArea.value = url;
      window.document.body.appendChild(textArea);
      textArea.select();
      window.document.execCommand('copy');
      window.document.body.removeChild(textArea);
      alert('Document link copied to clipboard!');
    }
  };

  return (
    <Card className="hover:shadow-lg transition-shadow duration-200">
      <CardHeader className="pb-3">
        <div className="flex items-start justify-between">
          <div className="flex-1">
            <CardTitle className="text-lg font-semibold text-foreground line-clamp-2">
              {document.title}
            </CardTitle>
            <div className="flex items-center gap-2 mt-2">
              <Badge variant="secondary" className="text-xs">
                {document.type}
              </Badge>
              {document.category && (
                <Badge variant="outline" className="text-xs">
                  {document.category}
                </Badge>
              )}
            </div>
          </div>
          <DropdownMenu>
            <DropdownMenuTrigger asChild>
              <Button variant="ghost" size="sm" className="h-8 w-8 p-0">
                <MoreHorizontal className="h-4 w-4" />
              </Button>
            </DropdownMenuTrigger>
            <DropdownMenuContent align="end" className="w-48">
              <DropdownMenuItem onClick={handleCopyLink}>
                <ExternalLink className="mr-2 h-4 w-4" />
                Copy Link
              </DropdownMenuItem>
              <DropdownMenuSeparator />
              <DropdownMenuItem onClick={handleNativeShare}>
                <Share className="mr-2 h-4 w-4" />
                Share / AirDrop
              </DropdownMenuItem>
            </DropdownMenuContent>
          </DropdownMenu>
        </div>
      </CardHeader>
      
      <CardContent className="pt-0">
        <p className="text-sm text-muted-foreground mb-4 line-clamp-2">
          {document.description}
        </p>
        
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-1 text-xs text-muted-foreground">
            <FileText className="h-3 w-3" />
            <span>Updated {formattedDate}</span>
          </div>
          
          <div className="flex items-center gap-1">
            <Button
              variant="outline"
              size="sm"
              onClick={handleEmailShare}
              className="h-8 px-2"
            >
              <Mail className="h-3 w-3 mr-1" />
              Email
            </Button>
            
            <Button
              variant="outline"
              size="sm"
              onClick={handleDownload}
              className="h-8 px-2"
            >
              <Download className="h-3 w-3 mr-1" />
              Save
            </Button>
            
            <Button
              size="sm"
              onClick={handleOpenForm}
              className="h-8 px-3"
            >
              Open
            </Button>
          </div>
        </div>
      </CardContent>
    </Card>
  );
}