import { Document } from "@shared/schema";

export interface EmailOptions {
  to?: string;
  subject: string;
  body: string;
  attachmentName?: string;
  attachmentContent?: string;
}

// Generate document content for email attachment
export function generateDocumentContent(document: Document): string {
  const currentDate = new Date().toLocaleDateString();
  const currentTime = new Date().toLocaleTimeString();
  
  return `
${document.title}
Generated from LOADMworkflow

Document Information:
- Title: ${document.title}
- Type: ${document.type}
- Description: ${document.description}
- Last Updated: ${new Date(document.lastUpdated).toLocaleString()}
- Generated: ${currentDate} at ${currentTime}

This document template can be filled out and submitted through the LOADMworkflow system.

For more information, visit the LOADMworkflow application.

---
Generated by LOADMworkflow Document Management System
`.trim();
}

// Create mailto link with document information
export function createDocumentMailtoLink(document: Document, recipientEmail?: string): string {
  const subject = encodeURIComponent(`${document.title} - LOADMworkflow Document`);
  const documentContent = generateDocumentContent(document);
  
  const body = encodeURIComponent(
    `Hello,\n\n` +
    `Please find the ${document.title} document information below:\n\n` +
    `${documentContent}\n\n` +
    `You can access and fill out this document at: [LOADMworkflow Application]\n\n` +
    `Best regards`
  );
  
  const to = recipientEmail ? `${encodeURIComponent(recipientEmail)}` : '';
  return `mailto:${to}?subject=${subject}&body=${body}`;
}

// Create a downloadable file for email attachment
export function createDocumentFile(document: Document): Blob {
  const content = generateDocumentContent(document);
  return new Blob([content], { type: 'text/plain' });
}

// Download document as file for manual email attachment
export function downloadDocumentForEmail(doc: Document): void {
  const blob = createDocumentFile(doc);
  const url = URL.createObjectURL(blob);
  const link = window.document.createElement('a');
  link.href = url;
  link.download = `${doc.title.replace(/\s+/g, '_')}.txt`;
  window.document.body.appendChild(link);
  link.click();
  window.document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

// Open email client with option to download attachment
export function openEmailWithDocument(document: Document, recipientEmail?: string): void {
  // First, download the document file
  downloadDocumentForEmail(document);
  
  // Then open email client
  const mailtoLink = createDocumentMailtoLink(document, recipientEmail);
  window.open(mailtoLink, '_blank');
}